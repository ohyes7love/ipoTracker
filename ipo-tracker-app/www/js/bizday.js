/**
 * 해당 날짜가 한국 증권시장 휴장일인지 확인합니다.
 * (주말 또는 공휴일)
 * @param {Date} date
 * @returns {boolean}
 */
function isNonBusinessDay(date) {
    const dow = date.getDay(); // 0=일, 6=토
    if (dow === 0 || dow === 6) return true;
    const ymd = date.toISOString().slice(0, 10);
    return _KR_HOLIDAYS.has(ymd);
}

/**
 * 날짜 문자열(YYYY-MM-DD) 또는 Date를 받아
 * 영업일 n일 뒤 날짜를 반환합니다.
 * n=0 이면 해당 날짜가 영업일이면 그대로, 아니면 다음 영업일.
 *
 * @param {string|Date} startDate - 기준 날짜
 * @param {number} n - 더할 영업일 수
 * @returns {Date} 결과 날짜 (시각 00:00:00)
 */
function addBusinessDays(startDate, n) {
    const d = typeof startDate === 'string'
        ? new Date(startDate + 'T00:00:00')
        : new Date(startDate);
    d.setHours(0, 0, 0, 0);
    let count = 0;
    while (count < n) {
        d.setDate(d.getDate() + 1);
        if (!isNonBusinessDay(d)) count++;
    }
    return d;
}

/**
 * 매도일(soldDate) 기준으로 출금 가능일을 계산합니다.
 * 한국 주식 결제 주기: 매도일 포함 영업일 3일째 (T+2)
 *   = 매도일 다음 2 영업일 후
 *
 * @param {string} soldDate - 매도일 (YYYY-MM-DD)
 * @returns {Date} 출금 가능일 (시각 00:00:00)
 */
function getWithdrawDate(soldDate) {
    return addBusinessDays(soldDate, 2);
}

/**
 * 출금 가능일까지 남은 영업일 수를 반환합니다.
 * 오늘이 출금 가능일 이후면 0 반환.
 *
 * @param {string} soldDate - 매도일 (YYYY-MM-DD)
 * @returns {number} 남은 영업일 (0 = 오늘 출금 가능)
 */
function daysUntilWithdraw(soldDate) {
    const today = new Date();
    today.setHours(0, 0, 0, 0);
    const wd = getWithdrawDate(soldDate);
    if (wd <= today) return 0;
    // 오늘~출금일 사이 달력일 차이(단순 표시용)
    return Math.round((wd - today) / 86400000);
}
